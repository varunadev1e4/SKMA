-- Update 25: employee features (daily tasks, suggestions and problem reports, sales-return notes,
-- fund top-up requests, blind stock count, delivered-bill tags, push notification devices).
-- Run ONCE after migration-23.sql and migration-24.sql. Safe to run again. For BOTH shops.
-- Employees can only add / read what is listed below. They never get stock, customer or sales data.

-- ---------- Daily tasks (you write them, employees tick them) ----------
create table if not exists emp_tasks (
  id bigint generated by default as identity primary key,
  emp_id bigint references employees(id) on delete cascade,            -- empty = for everyone
  title text not null, details text, due_d date,
  done boolean not null default false,
  done_by bigint references employees(id) on delete set null, done_at timestamptz, done_note text,
  created_at timestamptz default now()
);
create index if not exists emp_tasks_emp on emp_tasks(emp_id, done);

-- ---------- Low stock / new product suggestions and shop problems ----------
create table if not exists staff_reports (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  kind text not null check (kind in ('low','new','issue')),
  title text not null, details text,
  status text not null default 'open' check (status in ('open','done')),
  owner_note text,
  created_at timestamptz default now()
);
create index if not exists staff_reports_status on staff_reports(status, created_at);

-- ---------- Sales-return notes (written by employees, acted on by you) ----------
create table if not exists field_returns (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  d date not null default current_date,
  shop_name text not null, product text not null, batch text, qty numeric not null, exp text,
  reason text, note text,
  status text not null default 'new' check (status in ('new','done')),
  owner_note text,
  created_at timestamptz default now()
);
create index if not exists field_returns_status on field_returns(status, created_at);

-- ---------- Requests to top up the shop fund ----------
create table if not exists fund_requests (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  amount numeric not null check (amount > 0), note text,
  status text not null default 'open' check (status in ('open','done','rejected')),
  created_at timestamptz default now()
);

-- ---------- Blind stock count ----------
create table if not exists counts (
  id bigint generated by default as identity primary key,
  title text not null, status text not null default 'open' check (status in ('open','closed')),
  created_at timestamptz default now()
);
create table if not exists count_items (                       -- what employees see: no system quantity here
  id bigint generated by default as identity primary key,
  count_id bigint not null references counts(id) on delete cascade,
  product text not null, company text, pack text, batch text, exp text, rack text,
  counted_qty numeric, counted_by bigint references employees(id) on delete set null, counted_at timestamptz, note text
);
create index if not exists count_items_count on count_items(count_id);
create table if not exists count_expected (                    -- system quantity: owner only
  id bigint generated by default as identity primary key,
  item_id bigint not null unique references count_items(id) on delete cascade,
  qty numeric
);

-- ---------- Which employee delivered which bill ----------
create table if not exists bill_tags (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  bill_no text not null, fy text not null,                       -- fy = year the financial year starts, e.g. 2026
  d date not null default current_date,
  created_at timestamptz default now(),
  unique (bill_no, fy)
);
create index if not exists bill_tags_emp on bill_tags(emp_id, d);

-- ---------- Phones that should receive push notifications ----------
create table if not exists push_subs (
  id bigint generated by default as identity primary key,
  email text not null, role text, emp_id bigint,
  endpoint text not null unique, p256dh text not null, auth text not null,
  created_at timestamptz default now()
);

-- ---------- Security ----------
do $$
declare t text;
begin
  foreach t in array array['emp_tasks','staff_reports','field_returns','fund_requests','counts','count_items','count_expected','bill_tags','push_subs'] loop
    execute format('alter table %I enable row level security', t);
  end loop;
end $$;

-- owners: everything on the new tables
do $$
declare t text;
begin
  foreach t in array array['emp_tasks','staff_reports','field_returns','fund_requests','counts','count_items','count_expected','bill_tags'] loop
    execute format('drop policy if exists "owner all" on %I', t);
    execute format('create policy "owner all" on %I for all to authenticated using (is_owner()) with check (is_owner())', t);
  end loop;
end $$;

-- employees
drop policy if exists "task staff read" on emp_tasks;
create policy "task staff read" on emp_tasks for select to authenticated using (is_staff() and (emp_id = my_emp() or emp_id is null));

drop policy if exists "rep staff read" on staff_reports;  drop policy if exists "rep staff add" on staff_reports;
create policy "rep staff read" on staff_reports for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "rep staff add" on staff_reports for insert to authenticated with check (is_staff() and emp_id = my_emp() and status = 'open' and owner_note is null);

drop policy if exists "ret staff read" on field_returns;  drop policy if exists "ret staff add" on field_returns;
create policy "ret staff read" on field_returns for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "ret staff add" on field_returns for insert to authenticated with check (is_staff() and emp_id = my_emp() and status = 'new' and owner_note is null);

drop policy if exists "req staff read" on fund_requests;  drop policy if exists "req staff add" on fund_requests;
create policy "req staff read" on fund_requests for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "req staff add" on fund_requests for insert to authenticated with check (is_staff() and emp_id = my_emp() and status = 'open');

drop policy if exists "cnt staff read" on counts;  drop policy if exists "cni staff read" on count_items;
create policy "cnt staff read" on counts for select to authenticated using (is_staff() and status = 'open');
create policy "cni staff read" on count_items for select to authenticated
  using (is_staff() and exists (select 1 from counts c where c.id = count_id and c.status = 'open'));

drop policy if exists "tag staff read" on bill_tags;  drop policy if exists "tag staff delete" on bill_tags;
create policy "tag staff read" on bill_tags for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "tag staff delete" on bill_tags for delete to authenticated using (is_staff() and emp_id = my_emp() and created_at > now() - interval '1 day');

drop policy if exists "push own" on push_subs;
create policy "push own" on push_subs for all to authenticated using (email = my_email()) with check (email = my_email());

-- ---------- Small functions employees may call (they cannot change those tables directly) ----------
create or replace function complete_task(p_id bigint, p_done boolean, p_note text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not is_staff() then raise exception 'not allowed'; end if;
  update emp_tasks set done = p_done, done_by = case when p_done then my_emp() end, done_at = case when p_done then now() end, done_note = case when p_done then p_note end
   where id = p_id and (emp_id = my_emp() or emp_id is null);
end $$;

create or replace function submit_count(p_item bigint, p_qty numeric, p_note text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not is_staff() then raise exception 'not allowed'; end if;
  if p_qty is null or p_qty < 0 then raise exception 'enter the counted quantity'; end if;
  update count_items i set counted_qty = p_qty, counted_by = my_emp(), counted_at = now(), note = p_note
   where i.id = p_item and exists (select 1 from counts c where c.id = i.count_id and c.status = 'open');
end $$;

-- Tag a bill as delivered by me. Returns 'ok', 'unknown' (number not in the app yet, send p_force = true to tag anyway)
-- or 'taken:<name>' (someone else already tagged it). It never returns any bill details.
create or replace function tag_bill(p_bill text, p_force boolean default false) returns text
language plpgsql security definer set search_path = public as $$
declare v_b text := upper(btrim(p_bill)); v_y int := extract(year from current_date)::int; v_fy text; v_start date; v_who text; v_seen boolean;
begin
  if not is_staff() then raise exception 'not allowed'; end if;
  if v_b is null or v_b = '' then raise exception 'enter the bill number'; end if;
  if extract(month from current_date) < 4 then v_y := v_y - 1; end if;
  v_fy := v_y::text; v_start := make_date(v_y, 4, 1);
  select e.name into v_who from bill_tags t join employees e on e.id = t.emp_id where t.bill_no = v_b and t.fy = v_fy;
  if v_who is not null then return 'taken:' || v_who; end if;
  select exists (select 1 from sales_lines s where s.kind = 'S' and upper(btrim(s.bill_no)) = v_b and s.d >= v_start)
      or exists (select 1 from bill_heads h where upper(btrim(h.feed_no)) = v_b and h.d >= v_start)
      or exists (select 1 from pending_bills p where p.kind = 'R' and upper(btrim(p.bill_no)) = v_b and p.bill_date >= v_start)
    into v_seen;
  if not v_seen and not coalesce(p_force, false) then return 'unknown'; end if;
  insert into bill_tags (emp_id, bill_no, fy) values (my_emp(), v_b, v_fy);
  return 'ok';
end $$;
revoke execute on function complete_task(bigint, boolean, text), submit_count(bigint, numeric, text), tag_bill(text, boolean) from public, anon;
grant execute on function complete_task(bigint, boolean, text), submit_count(bigint, numeric, text), tag_bill(text, boolean) to authenticated;

-- ---------- Backup restore helper knows the new tables ----------
create or replace function reset_sequences() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['temp_bills','employees','emp_entries','expenses','directory','directory_people','temp_returns','temp_collections','trips','emp_cash','app_roles','shop_fund',
                           'emp_tasks','staff_reports','field_returns','fund_requests','counts','count_items','count_expected','bill_tags'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))', t, t, t);
  end loop;
end $$;
revoke execute on function reset_sequences() from public, anon, authenticated;
grant execute on function reset_sequences() to service_role;
