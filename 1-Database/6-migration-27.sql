-- ---------- Bills that do not need delivery (counter sales etc.) ----------
create table if not exists delivery_skip (
  id bigint generated by default as identity primary key,
  bill_no text not null, fy text not null, note text,
  created_at timestamptz default now(),
  unique (bill_no, fy)
);
alter table delivery_skip enable row level security;
drop policy if exists "owner all" on delivery_skip;
create policy "owner all" on delivery_skip for all to authenticated using (is_owner()) with check (is_owner());

-- ---------- Activity log: written only by database triggers, read only by owners, never edited ----------
create table if not exists activity_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  actor text, actor_role text,
  action text not null,            -- INSERT | UPDATE | DELETE
  tbl text not null, row_id bigint,
  old_data jsonb, new_data jsonb   -- for updates: only the columns that changed
);
create index if not exists activity_log_at on activity_log(at desc);
create index if not exists activity_log_tbl on activity_log(tbl, at desc);
alter table activity_log enable row level security;
drop policy if exists "owner read" on activity_log;
create policy "owner read" on activity_log for select to authenticated using (is_owner());
revoke insert, update, delete, truncate on activity_log from anon, authenticated;

create or replace function log_activity() returns trigger language plpgsql security definer set search_path = public as $$
declare v_old jsonb; v_new jsonb; v_id bigint; v_actor text := coalesce(nullif(my_email(), ''), 'system'); v_role text;
begin
  select role into v_role from app_roles where email = v_actor limit 1;
  if TG_OP = 'INSERT' then v_new := to_jsonb(NEW); v_id := NEW.id;
  elsif TG_OP = 'DELETE' then v_old := to_jsonb(OLD); v_id := OLD.id;
  else
    v_id := NEW.id;
    select jsonb_object_agg(n.k, n.v), jsonb_object_agg(o.k, o.v) into v_new, v_old
      from jsonb_each(to_jsonb(NEW)) n(k, v) join jsonb_each(to_jsonb(OLD)) o(k, v) on o.k = n.k
     where n.v is distinct from o.v;
    if v_new is null then return null; end if;      -- nothing really changed
  end if;
  insert into activity_log (actor, actor_role, action, tbl, row_id, old_data, new_data)
  values (v_actor, coalesce(v_role, case when v_actor = 'system' then 'system' end), TG_OP, TG_TABLE_NAME, v_id, v_old, v_new);
  return null;
exception when others then
  return null;      -- logging must never stop a real save
end $$;
revoke execute on function log_activity() from public, anon, authenticated;

