-- Update 33: attendance with arrival and leaving times. Run ONCE after 11-grants-new-projects.sql. Safe to run again. For SKMA.
--
-- Employees tap "I'm in" / "I'm leaving" on their own phone. The TIME is taken by the server (the phone's clock is never used)
-- and, if the owner has saved the shop's location, the tap is accepted only within the set distance of the shop.
-- Late marks, hours worked, "forgot to punch out" and an automatic half day for very short days are worked out from these times.
-- The Desk and the owners can fix a time: the original time and who changed it are always kept, and it shows in the activity log.

-- ---------- Settings (one row, owners only) ----------
create table if not exists shop_settings (
  id int primary key default 1 check (id = 1),
  shop_lat double precision, shop_lng double precision,
  radius_m int not null default 150,
  start_time time not null default '09:30',
  grace_min int not null default 10,
  half_day_hours numeric not null default 4,
  updated_at timestamptz default now(), updated_by text
);
insert into shop_settings (id) values (1) on conflict (id) do nothing;
alter table shop_settings enable row level security;
drop policy if exists "ss owner" on shop_settings;
create policy "ss owner" on shop_settings for all to authenticated using (is_owner()) with check (is_owner());

-- ---------- One row per employee per day ----------
create table if not exists att_punches (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  d date not null,
  t_in timestamptz, t_out timestamptz,
  in_lat double precision, in_lng double precision, in_acc int, in_dist int,
  out_lat double precision, out_lng double precision, out_acc int, out_dist int,
  source text not null default 'self',          -- self | desk | owner
  auto_half boolean not null default false,     -- a half day was marked automatically because the day was very short
  orig_in timestamptz, orig_out timestamptz,    -- the first values, kept when a time is fixed
  fixed_by text, fixed_at timestamptz, note text,
  created_at timestamptz default now(),
  unique (emp_id, d)
);
create index if not exists att_punches_d on att_punches(d);
alter table att_punches enable row level security;
drop policy if exists "ap owner" on att_punches;       create policy "ap owner" on att_punches for all to authenticated using (is_owner()) with check (is_owner());
drop policy if exists "ap own read" on att_punches;    create policy "ap own read" on att_punches for select to authenticated using (is_staff() and emp_id = my_emp());
drop policy if exists "ap desk read" on att_punches;   create policy "ap desk read" on att_punches for select to authenticated using (is_desk());
-- Nobody but an owner can write directly: employees and the Desk go through the two functions below.

drop trigger if exists log_att_punches on att_punches;
create trigger log_att_punches after insert or update or delete on att_punches for each row execute function log_activity();

-- ---------- Settings an employee needs to see (never the shop's exact spot) ----------
create or replace function att_config() returns jsonb language sql security definer set search_path = public stable as $$
  select jsonb_build_object('start_time', to_char(start_time, 'HH24:MI'), 'grace_min', grace_min, 'half_day_hours', half_day_hours,
                            'radius_m', radius_m, 'has_location', shop_lat is not null)
  from shop_settings where id = 1 and (is_staff() or is_owner());
$$;

-- ---------- Distance in metres between two points ----------
create or replace function att_dist(lat1 double precision, lng1 double precision, lat2 double precision, lng2 double precision) returns int
language sql immutable as $$
  select round(2 * 6371000 * asin(sqrt(least(1, power(sin(radians(lat2 - lat1) / 2), 2)
         + cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lng2 - lng1) / 2), 2)))))::int;
$$;

-- ---------- The employee taps In or Out ----------
create or replace function att_punch(p_dir text, p_lat double precision, p_lng double precision, p_acc double precision)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_emp bigint := my_emp();
  e employees; s shop_settings; r att_punches;
  v_today date := (now() at time zone 'Asia/Kolkata')::date;
  v_dist int; v_hrs numeric;
begin
  if v_emp is null or not is_staff() then raise exception 'This login is not linked to an employee.'; end if;
  select * into e from employees where id = v_emp;
  if not found or not coalesce(e.active, true) then raise exception 'This employee is not active.'; end if;
  if coalesce(e.no_attendance, false) then raise exception 'Attendance is not tracked for this person.'; end if;
  if p_dir not in ('in', 'out') then raise exception 'Unknown action.'; end if;
  select * into s from shop_settings where id = 1;

  if s.shop_lat is not null then
    if p_lat is null or p_lng is null then raise exception 'Your location is needed. Allow location for this app in the phone settings, then try again.'; end if;
    if coalesce(p_acc, 0) > 300 then raise exception 'Your location is not accurate enough (about % m). Turn on GPS, step near a window or outside the shop door, and try again.', round(p_acc)::int; end if;
    v_dist := att_dist(p_lat, p_lng, s.shop_lat, s.shop_lng);
    if v_dist > s.radius_m then raise exception 'You are about % m from the shop. You can punch only at the shop.', v_dist; end if;
  end if;

  if p_dir = 'in' then
    insert into att_punches (emp_id, d, t_in, in_lat, in_lng, in_acc, in_dist, source)
    values (v_emp, v_today, now(), p_lat, p_lng, round(p_acc)::int, v_dist, 'self')
    on conflict (emp_id, d) do update set t_in = excluded.t_in, in_lat = excluded.in_lat, in_lng = excluded.in_lng,
        in_acc = excluded.in_acc, in_dist = excluded.in_dist
      where att_punches.t_in is null
    returning * into r;
    if not found then raise exception 'You are already punched in today.'; end if;
  else
    select * into r from att_punches where emp_id = v_emp and d = v_today;
    if not found or r.t_in is null then raise exception 'You have not punched in today.'; end if;
    if r.t_out is not null then raise exception 'You are already punched out today.'; end if;
    if now() - r.t_in < interval '3 minutes' then raise exception 'You punched in just now. Wait a few minutes before punching out.'; end if;
    update att_punches set t_out = now(), out_lat = p_lat, out_lng = p_lng, out_acc = round(p_acc)::int, out_dist = v_dist
     where id = r.id returning * into r;
    v_hrs := extract(epoch from (r.t_out - r.t_in)) / 3600.0;
    if v_hrs < s.half_day_hours
       and not exists (select 1 from emp_entries where emp_id = v_emp and d = v_today and kind in ('absent', 'half', 'paidleave')) then
      insert into emp_entries (emp_id, d, kind, amount, note) values (v_emp, v_today, 'half', 0.5, 'auto: short hours');
      update att_punches set auto_half = true where id = r.id returning * into r;
    end if;
  end if;
  return to_jsonb(r);
end $$;

-- ---------- The Desk or an owner fixes (or adds) a time ----------
create or replace function att_fix(p_emp bigint, p_d date, p_in time, p_out time, p_note text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_in timestamptz; v_out timestamptz; r att_punches; s shop_settings; v_hrs numeric;
  v_who text := coalesce(nullif(my_email(), ''), 'system');
begin
  if not (is_owner() or is_desk()) then raise exception 'Only the Desk or an owner can fix times.'; end if;
  if p_d > (now() at time zone 'Asia/Kolkata')::date then raise exception 'You cannot enter a time for a future day.'; end if;
  if not exists (select 1 from employees where id = p_emp) then raise exception 'Unknown employee.'; end if;
  select * into s from shop_settings where id = 1;

  if p_in is null and p_out is null then          -- both cleared: remove the day's punches (and an automatic half day)
    delete from emp_entries where emp_id = p_emp and d = p_d and kind = 'half' and note = 'auto: short hours';
    delete from att_punches where emp_id = p_emp and d = p_d;
    return null;
  end if;
  v_in  := case when p_in  is null then null else ((p_d::timestamp + p_in)  at time zone 'Asia/Kolkata') end;
  v_out := case when p_out is null then null else ((p_d::timestamp + p_out) at time zone 'Asia/Kolkata') end;
  if v_in is not null and v_out is not null and v_out <= v_in then raise exception 'Leaving time must be after the arrival time.'; end if;

  insert into att_punches (emp_id, d, t_in, t_out, source, fixed_by, fixed_at, note)
  values (p_emp, p_d, v_in, v_out, case when is_owner() then 'owner' else 'desk' end, v_who, now(), nullif(p_note, ''))
  on conflict (emp_id, d) do update set
    orig_in  = case when att_punches.fixed_at is null then att_punches.t_in  else att_punches.orig_in  end,
    orig_out = case when att_punches.fixed_at is null then att_punches.t_out else att_punches.orig_out end,
    t_in = excluded.t_in, t_out = excluded.t_out, source = excluded.source,
    fixed_by = excluded.fixed_by, fixed_at = excluded.fixed_at, note = excluded.note
  returning * into r;

  -- the automatic half day follows the corrected times
  if r.t_in is not null and r.t_out is not null then
    v_hrs := extract(epoch from (r.t_out - r.t_in)) / 3600.0;
    if v_hrs < s.half_day_hours then
      if not exists (select 1 from emp_entries where emp_id = p_emp and d = p_d and kind in ('absent', 'half', 'paidleave')) then
        insert into emp_entries (emp_id, d, kind, amount, note) values (p_emp, p_d, 'half', 0.5, 'auto: short hours');
        update att_punches set auto_half = true where id = r.id returning * into r;
      end if;
    elsif r.auto_half then
      delete from emp_entries where emp_id = p_emp and d = p_d and kind = 'half' and note = 'auto: short hours';
      update att_punches set auto_half = false where id = r.id returning * into r;
    end if;
  elsif r.auto_half then
    delete from emp_entries where emp_id = p_emp and d = p_d and kind = 'half' and note = 'auto: short hours';
    update att_punches set auto_half = false where id = r.id returning * into r;
  end if;
  return to_jsonb(r);
end $$;

