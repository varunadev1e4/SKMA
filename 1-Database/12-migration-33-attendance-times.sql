-- the golden-backup restore resets the id counters: include the new table
create or replace function reset_sequences() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['temp_bills','employees','emp_entries','expenses','directory','directory_people','temp_returns','temp_collections','trips','emp_cash','app_roles','shop_fund',
                           'emp_tasks','staff_reports','field_returns','fund_requests','counts','count_items','count_expected','bill_tags','delivery_skip','activity_log','att_punches'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))', t, t, t);
  end loop;
end $$;
revoke execute on function reset_sequences() from public, anon, authenticated;
grant execute on function reset_sequences() to service_role;
